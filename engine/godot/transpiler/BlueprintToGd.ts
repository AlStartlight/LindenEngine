/**
 * Blueprint to GDScript Transpiler
 * Transpiles Linden Blueprint graphs into typed, clean, indented GDScript.
 */

import { BlueprintGraph, BlueprintVariable } from '../../blueprints/BlueprintGraph'
import {
  BlueprintNode,
  BlueprintPin,
  BlueprintPinType,
  EventBeginPlay,
  EventTick,
  EventInputAction,
  EventOnOverlapBegin,
  BranchNode,
  SequenceNode,
  ForLoopNode,
  WhileLoopNode,
  DelayNode,
  PrintStringNode,
  SetActorLocationNode,
  DestroyActorNode,
  SpawnActorNode,
  GetVariableNode,
  SetVariableNode,
  MathAddNode,
  MathSubtractNode,
  MathMultiplyNode,
  MathDivideNode,
  CompareEqualNode,
  CompareGreaterNode,
  CompareLessNode,
  RotateNode,
} from '../../blueprints/BlueprintNode'
import { CompatReport } from '../report/CompatReport'

export class BlueprintTranspileError extends Error {
  constructor(message: string) {
    super(message)
    this.name = 'BlueprintTranspileError'
  }
}

export class BlueprintToGd {
  static transpile(
    graph: BlueprintGraph,
    baseClass: string = 'Node3D'
  ): { code: string; report: CompatReport } {
    const transpiler = new BlueprintToGd(graph, baseClass)
    return transpiler.execute()
  }

  private report: CompatReport = new CompatReport()

  constructor(
    private graph: BlueprintGraph,
    private baseClass: string = 'Node3D'
  ) {}

  public execute(): { code: string; report: CompatReport } {
    // 1. Detect infinite execution cycles (UT-14)
    this.detectIllegalCycles()

    const lines: string[] = []
    lines.push(`extends ${this.baseClass}`)
    lines.push(`# Generated by Linden Engine - Blueprint to GDScript Transpiler`)
    lines.push('')

    // 2. Class Variables
    const variables = Array.from(this.graph.variables.values())
    if (variables.length > 0) {
      lines.push('# Variables')
      for (const v of variables) {
        lines.push(this.emitVariable(v))
      }
      lines.push('')
    }

    // 3. Collect Event Entry Points
    const nodes = this.graph.getAllNodes()
    const beginPlayNode = nodes.find((n) => n instanceof EventBeginPlay)
    const tickNode = nodes.find((n) => n instanceof EventTick)
    const inputNodes = nodes.filter((n) => n instanceof EventInputAction)
    const overlapNodes = nodes.filter((n) => n instanceof EventOnOverlapBegin)

    // Check if overlap exists to hook up in _ready()
    const hasOverlap = overlapNodes.length > 0

    // _ready()
    if (beginPlayNode || hasOverlap) {
      lines.push('func _ready() -> void:')
      const readyBody: string[] = []
      if (hasOverlap) {
        readyBody.push('\tbody_entered.connect(_on_body_entered)')
      }
      if (beginPlayNode) {
        const statements = this.emitExecChain(beginPlayNode, 'Then', 1, new Set())
        readyBody.push(...statements)
      }
      if (readyBody.length === 0) {
        readyBody.push('\tpass')
      }
      lines.push(...readyBody)
      lines.push('')
    }

    // _process(delta: float)
    if (tickNode) {
      lines.push('func _process(delta: float) -> void:')
      const statements = this.emitExecChain(tickNode, 'Then', 1, new Set())
      if (statements.length === 0) {
        lines.push('\tpass')
      } else {
        lines.push(...statements)
      }
      lines.push('')
    }

    // _input(event: InputEvent)
    if (inputNodes.length > 0) {
      lines.push('func _input(event: InputEvent) -> void:')
      const inputBody: string[] = []
      for (const inNode of inputNodes) {
        const actionName = (inNode as any).actionName || 'ui_accept'
        inputBody.push(`\tif event.is_action_pressed("${actionName}"):`)
        const pressedStmts = this.emitExecChain(inNode, 'Pressed', 2, new Set())
        if (pressedStmts.length === 0) {
          inputBody.push('\t\tpass')
        } else {
          inputBody.push(...pressedStmts)
        }

        const releasedStmts = this.emitExecChain(inNode, 'Released', 2, new Set())
        if (releasedStmts.length > 0) {
          inputBody.push(`\tif event.is_action_released("${actionName}"):`)
          inputBody.push(...releasedStmts)
        }
      }
      lines.push(...inputBody)
      lines.push('')
    }

    // Collision signals: _on_body_entered
    if (hasOverlap) {
      lines.push('func _on_body_entered(body: Node) -> void:')
      const overlapBody: string[] = []
      for (const ovNode of overlapNodes) {
        const stmts = this.emitExecChain(ovNode, 'Then', 1, new Set())
        overlapBody.push(...stmts)
      }
      if (overlapBody.length === 0) {
        lines.push('\tpass')
      } else {
        lines.push(...overlapBody)
      }
      lines.push('')
    }

    const code = lines.join('\n').trimEnd() + '\n'
    return { code, report: this.report }
  }

  /**
   * Check for cycles in execution connections without loop / conditional boundary
   */
  private detectIllegalCycles(): void {
    const visited = new Set<string>()
    const recStack = new Set<string>()

    const checkCycle = (nodeId: string, path: string[]) => {
      visited.add(nodeId)
      recStack.add(nodeId)

      const node = this.graph.nodes.get(nodeId)
      if (node) {
        const execOutPins = node.outputPins.filter((p) => p.type === BlueprintPinType.EXEC)
        for (const pin of execOutPins) {
          const conns = this.graph.connections.filter(
            (c) => c.sourceNodeId === nodeId && c.sourcePinId === pin.id
          )
          for (const conn of conns) {
            const nextId = conn.targetNodeId
            const nextNode = this.graph.nodes.get(nextId)
            // Loops (ForLoop, WhileLoop) are allowed to have loop bodies, but direct uncontrolled cycles are not
            if (recStack.has(nextId)) {
              // Direct cycle back to an ancestor without exit
              const msg = `Infinite execution cycle detected in BlueprintGraph: ${path.join(' -> ')} -> ${nextNode?.name || nextId}`
              this.report.addError(msg, { nodeName: node.name })
              throw new BlueprintTranspileError(msg)
            }
            if (!visited.has(nextId)) {
              checkCycle(nextId, [...path, nextNode?.name || nextId])
            }
          }
        }
      }

      recStack.delete(nodeId)
    }

    const eventNodes = this.graph.getEventNodes()
    for (const evt of eventNodes) {
      if (!visited.has(evt.id)) {
        checkCycle(evt.id, [evt.name])
      }
    }
  }

  private emitVariable(v: BlueprintVariable): string {
    let gdType = 'Variant'
    let defaultVal = 'null'

    switch (v.type) {
      case BlueprintPinType.BOOLEAN:
        gdType = 'bool'
        defaultVal = v.defaultValue ? 'true' : 'false'
        break
      case BlueprintPinType.INTEGER:
        gdType = 'int'
        defaultVal = String(v.defaultValue ?? 0)
        break
      case BlueprintPinType.FLOAT:
        gdType = 'float'
        defaultVal = String(v.defaultValue ?? 0.0)
        if (!defaultVal.includes('.')) defaultVal += '.0'
        break
      case BlueprintPinType.STRING:
        gdType = 'String'
        defaultVal = JSON.stringify(v.defaultValue ?? '')
        break
      case BlueprintPinType.VECTOR3:
        gdType = 'Vector3'
        defaultVal = 'Vector3.ZERO'
        break
      default:
        gdType = 'Variant'
        defaultVal = 'null'
        break
    }

    return `var ${this.toSnakeCase(v.name)}: ${gdType} = ${defaultVal}`
  }

  /**
   * Traverse execution chain starting from an output pin
   */
  private emitExecChain(
    fromNode: BlueprintNode,
    pinName: string,
    indent: number,
    visited: Set<string>
  ): string[] {
    const pin = fromNode.outputPins.find((p) => p.name === pinName && p.type === BlueprintPinType.EXEC)
    if (!pin) return []

    const conns = this.graph.connections.filter(
      (c) => c.sourceNodeId === fromNode.id && c.sourcePinId === pin.id
    )

    const statements: string[] = []
    for (const conn of conns) {
      const targetNode = this.graph.nodes.get(conn.targetNodeId)
      if (targetNode) {
        statements.push(...this.emitNode(targetNode, indent, new Set(visited)))
      }
    }
    return statements
  }

  /**
   * Emit code for a specific execution node
   */
  private emitNode(node: BlueprintNode, indent: number, visited: Set<string>): string[] {
    const tabs = '\t'.repeat(indent)
    const statements: string[] = []

    if (visited.has(node.id)) {
      return statements
    }
    visited.add(node.id)

    // 1. BranchNode
    if (node instanceof BranchNode) {
      const condExpr = this.getInputValue(node, 'Condition', 'false')
      statements.push(`${tabs}if ${condExpr}:`)
      const trueStmts = this.emitExecChain(node, 'True', indent + 1, visited)
      if (trueStmts.length === 0) {
        statements.push(`${tabs}\tpass`)
      } else {
        statements.push(...trueStmts)
      }

      const falseStmts = this.emitExecChain(node, 'False', indent + 1, visited)
      if (falseStmts.length > 0) {
        statements.push(`${tabs}else:`)
        statements.push(...falseStmts)
      }
      return statements
    }

    // 2. ForLoopNode
    if (node instanceof ForLoopNode) {
      const first = this.getInputValue(node, 'First Index', '0')
      const last = this.getInputValue(node, 'Last Index', '10')
      statements.push(`${tabs}for i in range(${first}, (${last}) + 1):`)
      const bodyStmts = this.emitExecChain(node, 'Loop Body', indent + 1, visited)
      if (bodyStmts.length === 0) {
        statements.push(`${tabs}\tpass`)
      } else {
        statements.push(...bodyStmts)
      }

      // Next after loop completed
      const compStmts = this.emitExecChain(node, 'Completed', indent, visited)
      statements.push(...compStmts)
      return statements
    }

    // 3. WhileLoopNode
    if (node instanceof WhileLoopNode) {
      const cond = this.getInputValue(node, 'Condition', 'true')
      statements.push(`${tabs}while ${cond}:`)
      const bodyStmts = this.emitExecChain(node, 'Loop Body', indent + 1, visited)
      if (bodyStmts.length === 0) {
        statements.push(`${tabs}\tpass`)
      } else {
        statements.push(...bodyStmts)
      }

      const compStmts = this.emitExecChain(node, 'Completed', indent, visited)
      statements.push(...compStmts)
      return statements
    }

    // 4. SequenceNode
    if (node instanceof SequenceNode) {
      const execPins = node.outputPins.filter((p) => p.type === BlueprintPinType.EXEC)
      for (const ep of execPins) {
        const seqStmts = this.emitExecChain(node, ep.name, indent, visited)
        statements.push(...seqStmts)
      }
      return statements
    }

    // 5. DelayNode (UT-12)
    if (node instanceof DelayNode) {
      const duration = this.getInputValue(node, 'Duration', '1.0')
      statements.push(`${tabs}await get_tree().create_timer(${duration}).timeout`)
      statements.push(...this.emitExecChain(node, 'Completed', indent, visited))
      return statements
    }

    // 6. RotateNode (UT-10)
    if (node instanceof RotateNode) {
      const speed = this.getInputValue(node, 'Speed', '90.0')
      const axis = this.getInputValue(node, 'Axis', '"Y"').replace(/"/g, '').toUpperCase()
      if (axis === 'X') {
        statements.push(`${tabs}rotate_x(deg_to_rad(${speed}) * delta)`)
      } else if (axis === 'Z') {
        statements.push(`${tabs}rotate_z(deg_to_rad(${speed}) * delta)`)
      } else {
        statements.push(`${tabs}rotate_y(deg_to_rad(${speed}) * delta)`)
      }
      statements.push(...this.emitExecChain(node, 'Then', indent, visited))
      return statements
    }

    // 7. PrintStringNode
    if (node instanceof PrintStringNode) {
      const strVal = this.getInputValue(node, 'String', '"Hello"')
      statements.push(`${tabs}print(${strVal})`)
      statements.push(...this.emitExecChain(node, 'Then', indent, visited))
      return statements
    }

    // 8. SetVariableNode
    if (node instanceof SetVariableNode) {
      const varName = this.toSnakeCase(node.variableName)
      const val = this.getInputValue(node, 'Value', '0')
      statements.push(`${tabs}${varName} = ${val}`)
      statements.push(...this.emitExecChain(node, 'Then', indent, visited))
      return statements
    }

    // 9. DestroyActorNode
    if (node instanceof DestroyActorNode) {
      statements.push(`${tabs}queue_free()`)
      statements.push(...this.emitExecChain(node, 'Then', indent, visited))
      return statements
    }

    // 10. SpawnActorNode
    if (node instanceof SpawnActorNode) {
      statements.push(`${tabs}add_child(scene.instantiate())`)
      statements.push(...this.emitExecChain(node, 'Then', indent, visited))
      return statements
    }

    // 11. SetActorLocationNode
    if (node instanceof SetActorLocationNode) {
      const loc = this.getInputValue(node, 'New Location', 'Vector3.ZERO')
      statements.push(`${tabs}global_position = ${loc}`)
      statements.push(...this.emitExecChain(node, 'Then', indent, visited))
      return statements
    }

    // Unsupported node (UT-13)
    this.report.recordSkipped(
      undefined,
      node.displayName || node.name,
      node.category,
      `Unsupported blueprint node: ${node.displayName || node.name}`
    )
    statements.push(`${tabs}# UNSUPPORTED: ${node.displayName || node.name}`)

    // Continue chain if it has an exec output
    const defaultExec = node.getNextExecPin()
    if (defaultExec) {
      statements.push(...this.emitExecChain(node, defaultExec.name, indent, visited))
    }

    return statements
  }

  /**
   * Resolve and emit expression connected to an input pin
   */
  private getInputValue(node: BlueprintNode, pinName: string, fallback: string): string {
    const pin = node.inputPins.find((p) => p.name === pinName)
    if (!pin) return fallback

    const conn = this.graph.connections.find(
      (c) => c.targetNodeId === node.id && c.targetPinId === pin.id
    )

    if (!conn) {
      if (pin.defaultValue !== undefined && pin.defaultValue !== null) {
        if (typeof pin.defaultValue === 'string') return JSON.stringify(pin.defaultValue)
        if (typeof pin.defaultValue === 'boolean') return pin.defaultValue ? 'true' : 'false'
        if (typeof pin.defaultValue === 'number') return String(pin.defaultValue)
      }
      return fallback
    }

    const srcNode = this.graph.nodes.get(conn.sourceNodeId)
    if (!srcNode) return fallback

    return this.emitExpression(srcNode, conn.sourcePinId)
  }

  /**
   * Recursively emit pure expression node
   */
  private emitExpression(srcNode: BlueprintNode, pinId: string): string {
    if (srcNode instanceof GetVariableNode) {
      return this.toSnakeCase(srcNode.variableName)
    }

    if (srcNode instanceof EventTick) {
      return 'delta'
    }

    if (srcNode instanceof MathAddNode) {
      const a = this.getInputValue(srcNode, 'A', '0')
      const b = this.getInputValue(srcNode, 'B', '0')
      return `(${a} + ${b})`
    }

    if (srcNode instanceof MathSubtractNode) {
      const a = this.getInputValue(srcNode, 'A', '0')
      const b = this.getInputValue(srcNode, 'B', '0')
      return `(${a} - ${b})`
    }

    if (srcNode instanceof MathMultiplyNode) {
      const a = this.getInputValue(srcNode, 'A', '1')
      const b = this.getInputValue(srcNode, 'B', '1')
      return `(${a} * ${b})`
    }

    if (srcNode instanceof MathDivideNode) {
      const a = this.getInputValue(srcNode, 'A', '1')
      const b = this.getInputValue(srcNode, 'B', '1')
      return `(${a} / ${b})`
    }

    if (srcNode instanceof CompareEqualNode) {
      const a = this.getInputValue(srcNode, 'A', '0')
      const b = this.getInputValue(srcNode, 'B', '0')
      return `(${a} == ${b})`
    }

    if (srcNode instanceof CompareGreaterNode) {
      const a = this.getInputValue(srcNode, 'A', '0')
      const b = this.getInputValue(srcNode, 'B', '0')
      return `(${a} > ${b})`
    }

    if (srcNode instanceof CompareLessNode) {
      const a = this.getInputValue(srcNode, 'A', '0')
      const b = this.getInputValue(srcNode, 'B', '0')
      return `(${a} < ${b})`
    }

    return 'null'
  }

  private toSnakeCase(str: string): string {
    return str
      .replace(/\s+/g, '_')
      .replace(/([a-z])([A-Z])/g, '$1_$2')
      .toLowerCase()
  }
}
