// Writes specs/<category>/part-NNN.spec.ts files, PART_SIZE cases each
import { mkdirSync, rmSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { CATEGORIES, PART_SIZE } from './manifest.mjs'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
rmSync(join(root, 'specs'), { recursive: true, force: true })
let files = 0
let total = 0
for (const c of CATEGORIES) {
  const dir = join(root, 'specs', c.dir)
  mkdirSync(dir, { recursive: true })
  for (let start = 0, part = 1; start < c.count; start += PART_SIZE, part++) {
    const end = Math.min(start + PART_SIZE, c.count)
    writeFileSync(join(dir, `part-${String(part).padStart(3, '0')}.spec.ts`),
      `// Generated by tools/generate-parts.mjs — do not edit\nimport { defineSlice } from '../../lib/define'\nimport { cases } from '../../gen/${c.dir}'\n\ndefineSlice('${c.prefix}', ${JSON.stringify(c.title)}, cases, ${start}, ${end}, ${c.count})\n`)
    files++
  }
  total += c.count
}
console.log(`generated ${files} spec files for ${total} cases`)
